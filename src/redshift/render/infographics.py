log = get_logger("s08")

STAGE = "s08_infographic"

WIDTH, HEIGHT = 1080, 1920

#: §13.2 T6 — anchor 0.35 → arrow 0.40 → verb 0.20 → anchor 0.35 → result 0.40.
PROCESS_BEATS = {"anchor_a": 0.35, "arrow": 0.40, "verb": 0.20, "anchor_b": 0.35, "result": 0.40}

#: §13.3 — a card that lives under this is not readable at all.
MIN_CARD_S = 1.6
MAX_CARD_S = 3.4


@dataclass
class BrandTokens:
    """Everything a template needs from config/brand.yaml, resolved once."""

    bg: str
    bg_secondary: str
    accent: str
    accent_hot: str
    text: str
    muted: str
    gold: str
    font_head: str
    font_body: str
    font_num: str
    glow_text: str
    glow_soft: str
    radius: int
    grid: int

    @classmethod
    def from_config(cls, config: Config) -> BrandTokens:
        return cls(
            bg=config.brand("colors.bg_primary"),
            bg_secondary=config.brand("colors.bg_secondary"),
            accent=config.brand("colors.accent"),
            accent_hot=config.brand("colors.accent_hot"),
            text=config.brand("colors.text"),
            muted=config.brand("colors.muted"),
            gold=config.brand("colors.gold"),
            font_head=config.brand("fonts.head"),
            font_body=config.brand("fonts.body"),
            font_num=config.brand("fonts.num"),
            glow_text=config.brand("effects.glow_text"),
            glow_soft=config.brand("effects.glow_soft"),
            radius=int(config.brand("effects.radius_px")),
            grid=int(config.brand("effects.grid_unit_px")),
        )


@dataclass
class RenderedCard:
    spec: InfographicSpec
    html_path: Path
    image_path: Path | None = None
    duration_s: float = 2.4
    warnings: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.image_path is not None and self.image_path.exists()


