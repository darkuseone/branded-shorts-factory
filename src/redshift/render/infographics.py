def render_card(
    spec: InfographicSpec,
    config: Config,
    destination: Path,
    *,
    transparent: bool = True,
    icons: IconBank | None = None,
) -> RenderedCard:
    """HTML → PNG via headless Chromium. Falls back to HTML only if it is absent."""
    tokens = BrandTokens.from_config(config)
    destination.mkdir(parents=True, exist_ok=True)

    html_path = destination / f"{spec.shot_id}.html"
    html_path.write_text(build_html(spec, tokens, icons), encoding="utf-8")

    card = RenderedCard(
        spec=spec,
        html_path=html_path,
        duration_s=card_duration(spec.template, spec.items, spec.duration_s),
    )
    image_path = destination / f"{spec.shot_id}.png"
    if _screenshot(html_path, image_path, transparent=transparent):
        card.image_path = image_path
        log.info(
            "%s: %s card rendered (%.2fs on screen)",
            spec.shot_id,
            spec.template,
            card.duration_s,
            extra={"stage": STAGE},
        )
    else:
        card.warnings.append("no headless browser; the card exists as HTML only")
    return card


def _screenshot(html_path: Path, image_path: Path, *, transparent: bool) -> bool:
    """Shoot the card with Playwright's Chromium if it is installed."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        log.info("playwright not installed; skipping card screenshot", extra={"stage": STAGE})
        return False

    try:
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(
                executable_path=_chromium_path(),
                args=["--force-color-profile=srgb", "--no-sandbox"],
            )
            page = browser.new_page(
                viewport={"width": WIDTH, "height": HEIGHT},
                device_scale_factor=1,
            )
            page.goto(html_path.resolve().as_uri())
            # Drive the clock to the end instead of sleeping: entrance delays
            # run past 1.3s, and a fixed wait silently cropped late elements.
            page.evaluate(_FINISH_ANIMATIONS)
            page.wait_for_timeout(60)
            page.screenshot(path=str(image_path), omit_background=transparent)
            browser.close()
    except Exception as exc:  # a browser failure must not kill the run
        log.warning("card screenshot failed: %s", exc, extra={"stage": STAGE})
        return False
    return image_path.exists()


def _chromium_path() -> str | None:
    """Find a browser the image already ships.

    The runner pins its own Chromium under PLAYWRIGHT_BROWSERS_PATH, and the
    build must never download one: an offline Actions runner would hang there.
    Returning None lets Playwright use its own default when nothing is pinned.
    """
    override = os.environ.get("REDSHIFT_CHROMIUM")
    if override and Path(override).exists():
        return override
    root = Path(os.environ.get("PLAYWRIGHT_BROWSERS_PATH", "/opt/pw-browsers"))
    for pattern in (
        "chromium-*/chrome-linux/chrome",
        "chromium_headless_shell-*/chrome-linux/headless_shell",
    ):
        for candidate in sorted(root.glob(pattern), reverse=True):
            if candidate.is_file():
                return str(candidate)
    for name in ("chromium", "chromium-browser", "google-chrome"):
        found = shutil.which(name)
        if found:
            return found
    return None


def render_animation(
    card: RenderedCard,
    destination: Path,
    *,
    fps: int = 30,
    ffmpeg: str = "ffmpeg",
) -> Path | None:
    """Render the card as a real animation: WebM with alpha.

    Frames come from stepping the browser's animation clock, not from panning a
    still — the arrow has to actually draw itself and the bars have to actually
    grow. That is the difference between a slide and a shot.
    """
    if not shutil.which(ffmpeg):
        return None
    frames_dir = destination / f"{card.spec.shot_id}_frames"
    frames = _render_frames(card.html_path, frames_dir, card.duration_s, fps)
    if not frames:
        return None

    target = destination / f"{card.spec.shot_id}.webm"
    command = [
        ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
        "-framerate", str(fps), "-i", str(frames_dir / "f_%04d.png"),
        "-c:v", "libvpx-vp9", "-pix_fmt", "yuva420p", "-b:v", "4M", "-auto-alt-ref", "0",
        str(target),
    ]  # fmt: skip
    result = subprocess.run(command, capture_output=True, timeout=600, check=False)
    shutil.rmtree(frames_dir, ignore_errors=True)
    if result.returncode != 0 or not target.exists():
        log.warning(
            "card animation failed: %s",
            result.stderr.decode("utf-8", "replace")[:200],
            extra={"stage": STAGE},
        )
        return None
    log.info("%s: animated %.2fs at %dfps", card.spec.shot_id, card.duration_s, fps, extra={"stage": STAGE})
    return target


def _render_frames(html_path: Path, frames_dir: Path, duration: float, fps: int) -> list[Path]:
    """Shoot one PNG per frame with the animation clock pinned to that instant."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return []

    frames_dir.mkdir(parents=True, exist_ok=True)
    count = max(2, int(round(duration * fps)))
    written: list[Path] = []
    try:
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(
                executable_path=_chromium_path(),
                args=["--force-color-profile=srgb", "--no-sandbox"],
            )
            page = browser.new_page(viewport={"width": WIDTH, "height": HEIGHT}, device_scale_factor=1)
            page.goto(html_path.resolve().as_uri())
            page.evaluate(_PAUSE_ANIMATIONS)
            for index in range(count):
                page.evaluate(_SEEK_ANIMATIONS, index / fps * 1000.0)
                frame = frames_dir / f"f_{index:04d}.png"
                page.screenshot(path=str(frame), omit_background=True)
                written.append(frame)
            browser.close()
    except Exception as exc:
        log.warning("frame capture failed: %s", exc, extra={"stage": STAGE})
        return []
    return written


#: Pinning the clock makes every frame reproducible; without it the capture
#: races the browser and the same card renders differently each run.
_PAUSE_ANIMATIONS = "() => document.getAnimations().forEach(a => a.pause())"
_SEEK_ANIMATIONS = "t => document.getAnimations().forEach(a => { try { a.currentTime = t; } catch (e) {} })"
_FINISH_ANIMATIONS = """() => document.getAnimations().forEach(a => {
  try { a.finish(); } catch (e) { a.currentTime = 100000; }
})"""


def write_manifest(cards: list[RenderedCard], path: Path) -> Path:
    """`infographics.json` — timings the timeline needs (§13.4)."""
    payload = {
        "schema_version": "1.0",
        "cards": [
            {
                **card.spec.model_dump(),
                "file": str(card.image_path) if card.image_path else "",
                "html": str(card.html_path),
                "duration_s": card.duration_s,
                "warnings": card.warnings,
            }
            for card in cards
        ],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


