"""Stage 08 — the infographic engine (§13).

Cards are rendered by us, never generated by a model. Generative models lie in
numbers and labels, and a wrong figure on screen is the one mistake this channel
cannot make (§11.2). So: verified claims in, HTML+CSS out, a browser screenshot
or a WebM with alpha back.

Seven templates, all from the references the client picked (§1.4):

    BIG_NUMBER      one huge figure, counter animation
    BAR_RANK        ranked rows with growing bars      (Brand Analytics look)
    COMPARISON_AB   before/after either side of a rule
    TIMELINE        years on an axis, active point lit
    ICON_FACT_LIST  round icons plus short facts       (YouTube-stats look)
    PROCESS_ARROW   anchor → arrow → verb → anchor     ("X hacked Y")
    SCREEN_CARD     an article card in brand style

PROCESS_ARROW is the one the client described by hand: a ChatGPT icon, an arrow,
Hugging Face, and a breach. Its beat timing (§13.2 T6) is baked in so the card
drops straight into the 1.2-2.2s rhythm instead of fighting it.
"""

from __future__ import annotations

