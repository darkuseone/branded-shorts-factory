def _icon_capsule(icon: str, size: int = 120, *, danger: bool = False) -> str:
    """A logo in a brand capsule (§9.4): circle, faint fill, thin ring.

    `icon` is either a path to a downloaded logo or a keyword; a keyword falls
    back to a drawn glyph so a missing logo never leaves a hole in the card.
    """
    inner = (
        f'<img src="{html.escape(icon)}" alt="">'
        if icon and ("/" in icon or icon.endswith((".png", ".svg", ".jpg", ".webp")))
        else f'<span class="glyph">{_GLYPHS.get(icon, _GLYPHS["default"])}</span>'
    )
    classes = "capsule danger" if danger else "capsule"
    return f'<div class="{classes}" style="--size:{size}px">{inner}</div>'


#: Drawn fallbacks, so a card never waits on a logo download.
_GLYPHS = {
    "alert": "⚠",
    "lock": "🔒",
    "shield": "🛡",
    "ai": "◈",
    "data": "▤",
    "cloud": "☁",
    "rocket": "▲",
    "default": "◆",
}


def _source(spec: InfographicSpec) -> str:
    """§13.3: the source of a figure is always on the card, in small type."""
    if not spec.source:
        return ""
    return f'<div class="source">{html.escape(spec.source)}</div>'


def _highlight(text: str, accent: str) -> str:
    escaped = html.escape(text)
    if accent and accent in text:
        return escaped.replace(html.escape(accent), f"<mark>{html.escape(accent)}</mark>", 1)
    return escaped


def _numeric(value: str) -> float:
    digits = "".join(char for char in str(value) if char.isdigit() or char in ".,")
    try:
        return float(digits.replace(",", "."))
    except ValueError:
        return 0.0


def _peak(spec: InfographicSpec) -> float:
    return max((_numeric(item.value) for item in spec.items), default=0.0)


