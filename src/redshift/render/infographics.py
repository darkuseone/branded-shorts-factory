def build_html(spec: InfographicSpec, tokens: BrandTokens, icons: IconBank | None = None) -> str:
    """Render one card to a standalone HTML document.

    With an `IconBank`, company and app marks are resolved to inline data URIs
    before the template runs, so the templates themselves stay unaware of where
    an icon came from — a resolved mark and a drawn glyph reach them the same
    way.
    """
    body = _TEMPLATES[spec.template](_with_icons(spec, icons), tokens)
    return _PAGE.format(
        title=html.escape(spec.title or spec.template),
        width=WIDTH,
        height=HEIGHT,
        css=_base_css(tokens),
        body=body,
    )


def _with_icons(spec: InfographicSpec, icons: IconBank | None) -> InfographicSpec:
    """Swap icon keywords for real marks where the bank has one."""
    if icons is None or not spec.items:
        return spec
    resolved = spec.model_copy(deep=True)
    for item in resolved.items:
        # An explicit keyword wins as the lookup term; the label is the
        # fallback because "OpenAI" is what a card actually names.
        uri = icons.resolve(item.icon or item.label)
        if uri:
            item.icon = uri
    return resolved


def _big_number(spec: InfographicSpec, tokens: BrandTokens) -> str:
    item = spec.items[0] if spec.items else None
    value = html.escape(item.value if item else "")
    label = html.escape(item.label if item else "")
    return f"""
<div class="card center">
  <div class="eyebrow">{html.escape(spec.title)}</div>
  <div class="bignum" data-count="{value}">{value}</div>
  <div class="biglabel">{label}</div>
  {_source(spec)}
</div>"""


def _bar_rank(spec: InfographicSpec, tokens: BrandTokens) -> str:
    """Direct descendant of the Brand Analytics reference (§1.4)."""
    peak = _peak(spec)
    rows = []
    for index, item in enumerate(spec.items):
        share = (_numeric(item.value) / peak * 100) if peak else 0
        rows.append(
            f"""
  <div class="row" style="--delay:{index * 0.06:.2f}s">
    <div class="rowhead">
      <span class="rowlabel">{html.escape(item.label)}</span>
      <span class="rowvalue">{html.escape(item.value)}</span>
    </div>
    <div class="bartrack"><div class="bar" style="--w:{share:.1f}%"></div></div>
  </div>"""
        )
    return f"""
<div class="card">
  <div class="cardtitle">{html.escape(spec.title)}</div>
  <div class="rows">{"".join(rows)}</div>
  {_source(spec)}
</div>"""


def _comparison(spec: InfographicSpec, tokens: BrandTokens) -> str:
    left = spec.items[0] if spec.items else None
    right = spec.items[1] if len(spec.items) > 1 else None
    return f"""
<div class="card">
  <div class="cardtitle">{html.escape(spec.title)}</div>
  <div class="ab">
    <div class="abside" style="--delay:0s">
      {_icon_capsule(left.icon if left else "")}
      <div class="abvalue">{html.escape(left.value if left else "")}</div>
      <div class="ablabel">{html.escape(left.label if left else "")}</div>
    </div>
    <div class="abrule"></div>
    <div class="abside" style="--delay:.25s">
      {_icon_capsule(right.icon if right else "")}
      <div class="abvalue hot">{html.escape(right.value if right else "")}</div>
      <div class="ablabel">{html.escape(right.label if right else "")}</div>
    </div>
  </div>
  {_source(spec)}
</div>"""


def _timeline(spec: InfographicSpec, tokens: BrandTokens) -> str:
    points = []
    for index, item in enumerate(spec.items):
        active = " active" if item.note == "active" else ""
        points.append(
            f"""
    <div class="tlpoint{active}" style="--delay:{0.2 + index * 0.12:.2f}s">
      <div class="tldot"></div>
      <div class="tlyear">{html.escape(item.value or item.label)}</div>
      <div class="tlnote">{html.escape(item.label if item.value else "")}</div>
    </div>"""
        )
    return f"""
<div class="card">
  <div class="cardtitle">{html.escape(spec.title)}</div>
  <div class="tl"><div class="tlaxis"></div>{"".join(points)}</div>
  {_source(spec)}
</div>"""


def _icon_fact_list(spec: InfographicSpec, tokens: BrandTokens) -> str:
    rows = []
    for index, item in enumerate(spec.items[:5]):
        rows.append(
            f"""
  <div class="fact" style="--delay:{index * 0.09:.2f}s">
    {_icon_capsule(item.icon, size=72)}
    <div class="facttext">
      <span class="factvalue">{html.escape(item.value)}</span>
      <span class="factlabel">{html.escape(item.label)}</span>
    </div>
  </div>"""
        )
    return f"""
<div class="card">
  <div class="cardtitle">{html.escape(spec.title)}</div>
  <div class="facts">{"".join(rows)}</div>
  {_source(spec)}
</div>"""


def _process_arrow(spec: InfographicSpec, tokens: BrandTokens) -> str:
    """The client's own case: icon → hand-drawn arrow → verb → icon → breach.

    The arrow is a quadratic Bezier with a deliberate wobble: a perfectly
    straight arrow reads as PowerPoint, and this channel is not PowerPoint.
    """
    anchor_a = spec.items[0] if spec.items else None
    anchor_b = spec.items[1] if len(spec.items) > 1 else None
    result = spec.items[2] if len(spec.items) > 2 else None
    verb = spec.accent_word or "→"

    result_block = ""
    if result:
        result_block = f"""
  <div class="result" style="--delay:1.30s">
    {_icon_capsule(result.icon or "alert", size=140, danger=True)}
    <div class="resultlabel">{html.escape(result.label or result.value)}</div>
  </div>"""

    return f"""
<div class="card process">
  <div class="cardtitle">{html.escape(spec.title)}</div>
  <div class="chain">
    <div class="anchor" style="--delay:0s">
      {_icon_capsule(anchor_a.icon if anchor_a else "", size=180)}
      <div class="anchorlabel">{html.escape(anchor_a.label if anchor_a else "")}</div>
    </div>

    <div class="arrowbox">
      <svg viewBox="0 0 420 160" class="arrow" preserveAspectRatio="none">
        <defs>
          <marker id="head" markerWidth="9" markerHeight="9" refX="6" refY="4.5" orient="auto">
            <path d="M0,0 L9,4.5 L0,9 z" fill="{tokens.accent}"/>
          </marker>
        </defs>
        <path d="M 10,96 Q 200,34 400,88" fill="none" stroke="{tokens.accent}"
              stroke-width="6" stroke-linecap="round" marker-end="url(#head)"/>
      </svg>
      <div class="verb" style="--delay:0.75s">{html.escape(verb)}</div>
    </div>

    <div class="anchor" style="--delay:0.95s">
      {_icon_capsule(anchor_b.icon if anchor_b else "", size=180)}
      <div class="anchorlabel">{html.escape(anchor_b.label if anchor_b else "")}</div>
    </div>
  </div>
  {result_block}
  {_source(spec)}
</div>"""


def _screen_card(spec: InfographicSpec, tokens: BrandTokens) -> str:
    lead = spec.items[0].label if spec.items else ""
    date = spec.items[0].value if spec.items else ""
    return f"""
<div class="card">
  <div class="screencard">
    <div class="screenrule"></div>
    <div class="screenbody">
      <div class="screendomain">{html.escape(spec.source)}</div>
      <div class="screenhead">{_highlight(spec.title, spec.accent_word)}</div>
      <div class="screendate">{html.escape(date)}</div>
      <div class="screenlead">{html.escape(lead)}</div>
    </div>
  </div>
</div>"""


