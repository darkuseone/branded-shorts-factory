def choose_template(beat_text: str, items: list[dict[str, Any]]) -> str:
    """Pick a template from the shape of the fact, not from taste.

    §22.8 is explicit about one case: anything of the form "X did something to
    Y" is always PROCESS_ARROW. That is the client's own example and the most
    common shape in AI/IT news.
    """
    lowered = beat_text.lower()
    if any(verb in lowered for verb in _ACTION_VERBS):
        return "PROCESS_ARROW"
    if len(items) >= 3 and all(item.get("value") for item in items):
        return "BAR_RANK"
    if len(items) == 2:
        return "COMPARISON_AB"
    if len(items) == 1:
        return "BIG_NUMBER"
    if any(str(item.get("label", "")).strip().isdigit() for item in items):
        return "TIMELINE"
    return "ICON_FACT_LIST"


_ACTION_VERBS = (
    "взлом",
    "обош",
    "превзош",
    "обогн",
    "поглот",
    "купил",
    "запуст",
    "атаков",
    "подмен",
    "украл",
    "слил",
    "hack",
    "breach",
    "beat",
    "overtook",
    "acquired",
)


def card_duration(template: str, items: list[Any], requested: float = 0.0) -> float:
    """Clamp a card into the window where it is both readable and rhythmic."""
    # PROCESS_ARROW has its own beat sheet; everything else gets a second of
    # reading time per unit, plus the entrance.
    natural = sum(PROCESS_BEATS.values()) if template == "PROCESS_ARROW" else 1.0 + 0.55 * max(1, len(items))
    return round(max(MIN_CARD_S, min(requested or natural, MAX_CARD_S)), 3)


